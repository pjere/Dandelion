def measured_shape(commodity: str, year: int) -> dict[int, float] | None:
    """-> {month: mean-1 multiplier} for a year with measured history, else None.

    Normalized over the AVAILABLE months (partial years - 2026 - normalize over what exists, so the
    annual anchor applies to the observed-months mean; missing months fall back to the generic shape
    at the caller)."""
    hist = MONTHLY_HIST.get(commodity, {})
    months = {int(k[5:7]): v for k, v in hist.items() if int(k[:4]) == int(year)}
    if len(months) < 3:
        return None
    mean = sum(months.values()) / len(months)
    if mean <= 0:
        return None
    return {m: v / mean for m, v in months.items()}
